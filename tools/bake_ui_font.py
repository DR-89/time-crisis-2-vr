"""Bake the pause menu's Chakra Petch faces (tools/fonts, SIL OFL 1.1) into quest/ui_font_data.h.

The menu draws on the CPU into one texture (quest/quest_canvas.c), so the font ships as 4-bit glyph bitmaps at the few sizes
the layout uses: nothing is rasterized at runtime and no font library is linked. Run after changing a size or the character set:
    python tools/bake_ui_font.py
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / 'tools/fonts'
OUT = ROOT / 'quest/ui_font_data.h'
TEXT = [chr(c) for c in range(32, 127)] + [chr(0xB7), chr(0xD7), chr(0x2026), chr(0xB0)]   # ASCII, middle dot, times, ellipsis, degree
BIG = list(' 0123456789.:ABCDEFGHIJKLMNOPQRSTUVWXYZ-_')                     # room codes, names, addresses
# (C name, face, pixel size, characters): the sizes quest/quest_menu.c lays out with
FACES = [
    ('UI_M15', 'Medium', 15, TEXT), ('UI_M17', 'Medium', 17, TEXT), ('UI_M20', 'Medium', 20, TEXT),
    ('UI_B14', 'Bold', 14, TEXT), ('UI_B16', 'Bold', 16, TEXT), ('UI_B20', 'Bold', 20, TEXT), ('UI_B22', 'Bold', 22, TEXT),
    ('UI_B24', 'Bold', 24, TEXT), ('UI_B27', 'Bold', 27, TEXT), ('UI_B32', 'Bold', 32, TEXT),
    ('UI_B44', 'Bold', 44, BIG), ('UI_B76', 'Bold', 76, BIG),
]

def bake():
    bits = bytearray()
    glyph_rows, font_rows = [], []
    for cname, face, size, chars in FACES:
        font = ImageFont.truetype(str(FONTS / f'ChakraPetch-{face}.ttf'), size)
        ascent, descent = font.getmetrics()
        first = len(glyph_rows)
        for ch in chars:
            x0, y0, x1, y1 = font.getbbox(ch, anchor='ls')
            w, h = max(0, x1 - x0), max(0, y1 - y0)
            img = Image.new('L', (max(w, 1), max(h, 1)), 0)
            if w and h:
                ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor='ls')
            px = img.load()
            offset = len(bits)
            for y in range(h):
                for x in range(0, w, 2):
                    a = (px[x, y] + 8) * 15 // 255
                    b = (px[x + 1, y] + 8) * 15 // 255 if x + 1 < w else 0
                    bits.append(min(a, 15) << 4 | min(b, 15))
            advance = round(font.getlength(ch) * 16)
            glyph_rows.append(f'{{{ord(ch)},{x0},{y0},{w},{h},{advance},{offset}}}')
        font_rows.append((cname, size, ascent, descent, first, len(glyph_rows) - first))
    lines = ['/* Generated by tools/bake_ui_font.py from Chakra Petch (SIL Open Font License 1.1, tools/fonts/OFL.txt). Do not edit. */',
             '#pragma once', '#include <stdint.h>',
             '/* One glyph: code point, left bearing and top (pixels from the baseline, negative is up), size, advance in 1/16 px,',
             ' * and where its rows start in ui_font_bits (4-bit coverage, two pixels a byte, high nibble first). */',
             'typedef struct UiGlyph { uint16_t cp; int8_t x0,y0; uint8_t w,h; uint16_t advance; uint32_t offset; } UiGlyph;',
             'typedef struct UiFontData { int size,ascent,descent,first,count; } UiFontData;',
             'enum { ' + ','.join(f[0] for f in font_rows) + ',UI_FONT_COUNT };',
             'static const UiFontData ui_fonts[UI_FONT_COUNT]={' + ','.join(f'{{{s},{a},{d},{f},{n}}}' for _, s, a, d, f, n in font_rows) + '};',
             f'static const UiGlyph ui_glyphs[{len(glyph_rows)}]={{']
    for i in range(0, len(glyph_rows), 8):
        lines.append('    ' + ','.join(glyph_rows[i:i + 8]) + ',')
    lines.append('};')
    lines.append(f'static const uint8_t ui_font_bits[{len(bits)}]={{')
    for i in range(0, len(bits), 32):
        lines.append(''.join(f'{b},' for b in bits[i:i + 32]))
    lines.append('};')
    OUT.write_text('\n'.join(lines) + '\n', newline='\n')
    print(f'{OUT.relative_to(ROOT)}: {len(font_rows)} faces, {len(glyph_rows)} glyphs, {len(bits)} bytes')

if __name__ == '__main__':
    bake()
